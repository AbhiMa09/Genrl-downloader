def main():
    check_mode = '--check' in sys.argv

    with open(DESIGN_MD, 'r', encoding='utf-8') as f:
        content = f.read()

    tokens = parse_frontmatter(content)

    targets = {
        os.path.join(THEME_DIR, 'colors.dart'): generate_colors_dart(tokens['colors']),
        os.path.join(THEME_DIR, 'spacing.dart'): generate_spacing_dart(tokens['spacing'], tokens['rounded']),
        os.path.join(THEME_DIR, 'typography.dart'): generate_typography_dart(),
    }

    if check_mode:
        for path, code in targets.items():
            if not os.path.exists(path):
                print(f"[ERROR] Missing {path}. Run tools/generate_theme.py", file=sys.stderr)
                sys.exit(1)
            with open(path, 'r', encoding='utf-8') as f:
                current = f.read()
            if current != code:
                print(f"[ERROR] {path} is out of sync with {DESIGN_MD}!", file=sys.stderr)
                print("Run: python3 tools/generate_theme.py", file=sys.stderr)
                sys.exit(1)
        print("[OK] All Dart theme files are in sync with DESIGN.md")
        sys.exit(0)
    else:
        for path, code in targets.items():
            with open(path, 'w', encoding='utf-8') as f:
                f.write(code)
            print(f"[OK] Generated {path}")

if __name__ == '__main__':
    main()
