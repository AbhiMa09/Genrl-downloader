def parse_frontmatter(content: str):
    match = re.match(r'^---\s*\n(.*?)\n---', content, re.DOTALL)
    if not match:
        raise ValueError(f"Could not find YAML frontmatter in {DESIGN_MD}")
    raw_yaml = match.group(1)

    # Simple parser for the DESIGN.md structure
    current_section = None
    data = {'colors': {}, 'typography': {}, 'rounded': {}, 'spacing': {}}
    sub_key = None

    for line in raw_yaml.splitlines():
        trimmed = line.strip()
        if not trimmed or trimmed.startswith('#'):
            continue

        if not line.startswith(' ') and trimmed.endswith(':'):
            current_section = trimmed[:-1].strip()
            sub_key = None
            continue

        if current_section == 'colors':
            m = re.match(r'^\s*([a-z0-9\-]+):\s*[\'"]?#?([a-fA-F0-9]+)[\'"]?', line)
            if m:
                data['colors'][m.group(1)] = m.group(2).upper()

        elif current_section == 'spacing':
            m = re.match(r'^\s*([a-z0-9\-]+):\s*([0-9\.]+)rem', line)
            if m:
                data['spacing'][m.group(1)] = float(m.group(2)) * 16.0

        elif current_section == 'rounded':
            m = re.match(r'^\s*([a-zA-Z0-9\-]+):\s*([0-9\.]+)(rem|px)', line)
            if m:
                val = float(m.group(2)) * (16.0 if m.group(3) == 'rem' else 1.0)
                data['rounded'][m.group(1)] = val

        elif current_section == 'typography':
            if line.startswith('  ') and not line.startswith('    ') and trimmed.endswith(':'):
                sub_key = trimmed[:-1].strip()
                data['typography'][sub_key] = {}
            elif sub_key and line.startswith('    '):
                m = re.match(r'^\s*([a-zA-Z0-9]+):\s*[\'"]?([^\'"]+)[\'"]?', line)
                if m:
                    data['typography'][sub_key][m.group(1)] = m.group(2)

    return data

