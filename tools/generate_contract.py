#!/usr/bin/env python3
"""
Contract Generator & Validator for Genrl.
Single source of truth: core/contract/contract.json
Generates: app/lib/services/generated_contract.dart
Validates:
  1. Every core command is either called/implemented in UI (core_bridge.dart) or marked internal: true.
  2. If run with --check, fails if the generated file is stale or out of date.
"""

import json
import os
import sys

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
CONTRACT_PATH = os.path.join(REPO_ROOT, 'core', 'contract', 'contract.json')
DART_OUTPUT_PATH = os.path.join(REPO_ROOT, 'app', 'lib', 'services', 'generated_contract.dart')
BRIDGE_PATH = os.path.join(REPO_ROOT, 'app', 'lib', 'services', 'core_bridge.dart')

def load_contract():
    with open(CONTRACT_PATH, 'r', encoding='utf-8') as f:
        return json.load(f)

def validate_ui_coverage(contract):
    """Ensure every command is either marked internal or called in CoreBridge."""
    with open(BRIDGE_PATH, 'r', encoding='utf-8') as f:
        bridge_code = f.read()

    uncovered = []
    for cmd in contract.get('commands', []):
        name = cmd['name']
        is_internal = cmd.get('internal', False)
        ui_method = cmd.get('ui_method')

        if is_internal:
            continue

        # Check if the command or ui_method is present in core_bridge.dart
        found = False
        if ui_method and f"{ui_method}(" in bridge_code:
            found = True
        elif f"'{name}'" in bridge_code or f'"{name}"' in bridge_code:
            found = True

        if not found:
            uncovered.append(name)

    if uncovered:
        raise ValueError(
            f"Contract violation: Core commands {uncovered} are neither marked 'internal: true' "
            f"nor called by the UI bridge ({BRIDGE_PATH})."
        )

def generate_dart_code(contract):
    commands = contract.get('commands', [])
    queries = contract.get('queries', [])
    events = contract.get('events', [])

    lines = [
        "// GENERATED CODE - DO NOT MODIFY BY HAND",
        "// Source: core/contract/contract.json",
        "// Generated by: tools/generate_contract.py",
        "",
        "import '../models/activity_item.dart';",
        "import '../models/inbox_item.dart';",
        "import '../models/library_item.dart';",
        "import '../models/queue_item.dart';",
        "import '../models/system_status.dart';",
        "",
        "/// Metadata definition for a Core Command.",
        "class CoreCommandMeta {",
        "  final String name;",
        "  final String description;",
        "  final bool internal;",
        "  final String cli;",
        "  final String? uiMethod;",
        "",
        "  const CoreCommandMeta({",
        "    required this.name,",
        "    required this.description,",
        "    required this.internal,",
        "    required this.cli,",
        "    this.uiMethod,",
        "  });",
        "}",
        "",
        "/// Single source catalog of all Genrl core commands.",
        "class GenrlContract {",
        "  static const List<CoreCommandMeta> commands = [",
    ]

    for c in commands:
        ui_m = f"'{c.get('ui_method')}'" if c.get('ui_method') else "null"
        lines.append(
            f"    CoreCommandMeta(name: '{c['name']}', description: '{c['description']}', "
            f"internal: {str(c.get('internal', False)).lower()}, cli: '{c['cli']}', uiMethod: {ui_m}),"
        )

    lines.extend([
        "  ];",
        "",
        "  static const List<String> eventNames = [",
    ])

    for e in events:
        lines.append(f"    '{e['name']}',")

    lines.extend([
        "  ];",
        "}",
        "",
        "/// Abstract interface that CoreBridge satisfies.",
        "abstract class ICoreBridgeContract {",
    ])

    for q in queries:
        lines.append(f"  Future<{q['response']}> {q['name']}();")

    lines.extend([
        "}",
        "",
    ])

    return "\n".join(lines)

def main():
    check_mode = '--check' in sys.argv
    contract = load_contract()

    # Step 1: Validate UI coverage
    validate_ui_coverage(contract)

    # Step 2: Generate Dart code
    generated = generate_dart_code(contract)

    # Step 3: Handle --check or write
    if check_mode:
        if not os.path.exists(DART_OUTPUT_PATH):
            print(f"[ERROR] {DART_OUTPUT_PATH} does not exist. Run tools/generate_contract.py to generate.", file=sys.stderr)
            sys.exit(1)
        with open(DART_OUTPUT_PATH, 'r', encoding='utf-8') as f:
            existing = f.read()
        if existing != generated:
            print(f"[ERROR] Generated contract {DART_OUTPUT_PATH} is out of date!", file=sys.stderr)
            print("Run: python3 tools/generate_contract.py", file=sys.stderr)
            sys.exit(1)
        print("[OK] Generated contract is up-to-date and UI coverage is complete.")
        sys.exit(0)
    else:
        os.makedirs(os.path.dirname(DART_OUTPUT_PATH), exist_ok=True)
        with open(DART_OUTPUT_PATH, 'w', encoding='utf-8') as f:
            f.write(generated)
        print(f"[OK] Generated {DART_OUTPUT_PATH}")
        print(f"[OK] All {len(contract.get('commands', []))} commands verified (covered or internal).")

if __name__ == '__main__':
    main()
